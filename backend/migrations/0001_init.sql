CREATE TABLE IF NOT EXISTS payment_types (
  id CHAR(36) PRIMARY KEY,
  brand_id CHAR(36) NOT NULL,
  outlet_id CHAR(36) NULL,
  group_id CHAR(36) NOT NULL,
  code VARCHAR(40) NOT NULL DEFAULT '',
